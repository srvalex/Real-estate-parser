# --- Pydantic Models ---

class ListingData(BaseModel):
    description: str
    url: str
    hard_filters: List[str] # From /process-search logic
    soft_filters: List[str] # From /process-search logic

class EmbeddingRequest(BaseModel):
    listings: List[ListingData]

class SearchQuery(BaseModel):
    vibe_terms: List[str]
    url_filters: List[str]
    limit: int = 5

# --- Endpoints ---

@app.post("/embed")
async def store_listings(data: EmbeddingRequest):
    try:
        descriptions = [l.description for l in data.listings]
        urls = [l.url for l in data.listings]
        embeddings_list = model.encode(descriptions).tolist()

        # Create metadata including filters for filtering later
        metadatas = []
        for l in data.listings:
            meta = {"url": l.url}
            # ChromaDB 'where' filters work best with simple types or 'in' logic
            # We'll store filters as a JSON string or individual flags if preferred
            # For simplicity, we flag the presence of hard filters
            for hf in l.hard_filters:
                meta[f"filter_{hf.lower()}"] = True
            metadatas.append(meta)

        collection.upsert(
            documents=descriptions,
            embeddings=embeddings_list,
            metadatas=metadatas,
            ids=urls
        )

        return {"message": f"Stored {len(urls)} listings successfully."}

    except Exception as e:
        print(traceback.format_exc())
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/search-listings")
async def search_listings(query: SearchQuery):
    try:
        # 1. Encode the vibe terms (soft filters) into a single search vector
        search_text = " ".join(query.vibe_terms)
        query_embedding = model.encode([search_text]).tolist()[0]

        # 2. Build the 'where' filter for hard requirements
        # This ensures the results MUST match the extracted features
        where_clause = {}
        if query.url_filters:
            if len(query.url_filters) == 1:
                where_clause = {f"filter_{query.url_filters[0].lower()}": True}
            else:
                where_clause = {"$and": [{f"filter_{f.lower()}": True} for f in query.url_filters]}

        # 3. Query ChromaDB
        results = collection.query(
            query_embeddings=[query_embedding],
            n_results=query.limit,
            where=where_clause if where_clause else None
        )

        # 4. Format Results
        formatted_results = []
        for i in range(len(results['ids'][0])):
            formatted_results.append({
                "url": results['ids'][0][i],
                "description": results['documents'][0][i],
                "distance": results['distances'][0][i],
                "metadata": results['metadatas'][0][i]
            })

        return {
            "query_vibe": search_text,
            "matches": formatted_results
        }

    except Exception as e:
        print(traceback.format_exc())
        raise HTTPException(status_code=500, detail=str(e))

