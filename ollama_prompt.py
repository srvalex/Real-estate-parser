# ── 1. The Mapping Logic (The Dependency) ──────────────────────────────────

class KeywordMapper:
    def __init__(self):
        # In a real app, you'd load this from a .json file:
        # with open('mapping.json', 'r') as f: self.raw_map = json.load(f)
        self.raw_map = {
            "pet-friendly": ["pet-friendly", "accept animal de companie", "animal de companie", "animale de companie", "petfriendly"],
            "parcare": ["loc de parcare inclus", "garaj", "parcare in apropiere", "loc de parcare", "parcare subterana"],
            "gradina": ["curte", "gradina"],
            "metrou": ["metrou", "metro"],
            "centrala": ["centrala", "centrala propie"],
            "renovat": ["nou", "renovat", "utilat", "mobilat", "mobilat/utilat"]
        }
        # Flatten the map for O(1) lookup: {'garaj': 'parcare', 'metro': 'metrou', ...}
        self.lookup = {}
        for main_cat, variations in self.raw_map.items():
            for v in variations:
                self.lookup[v.lower()] = main_cat

    def normalize(self, extracted_keywords: List[str]) -> List[str]:
        normalized = set()
        for kw in extracted_keywords:
            kw_lower = kw.lower().strip()

            # 1. Check for exact match
            if kw_lower in self.lookup:
                normalized.add(self.lookup[kw_lower])
                continue

            # 2. Check if the extracted keyword CONTAINS or IS CONTAINED in our synonyms
            # This catches "loc de parcare" if your dict has "parcare"
            for variation, main_cat in self.lookup.items():
                if variation in kw_lower or kw_lower in variation:
                    normalized.add(main_cat)
                    break
        return list(normalized)

# Initialize the mapper once (Singleton pattern)
mapper_instance = KeywordMapper()

def get_mapper():
    """FastAPI Dependency provider."""
    return mapper_instance

# ── 2. Pydantic Schemas ──────────────────────────────────────────────────────

class UserQuery(BaseModel):
    text: str

class VibeSearch(BaseModel):
    hard_filters: List[str]  # These will be mapped to your dict
    soft_filters: List[str]  # These will be used for Vector Search later

# ── 3. FastAPI Application ───────────────────────────────────────────────────

app = FastAPI(title="Real Estate AI Agent")

@app.post("/process-search")
async def process_search(
    query: UserQuery,
    mapper: KeywordMapper = Depends(get_mapper)
):
    try:
        # Step A: Extract using Ollama
        system_prompt = f"""
        You are a real estate agent. Extract features from the user prompt.
        Known categories: {list(mapper.raw_map.keys())}.
        Put recognized categories or synonyms in 'hard_filters'.
        Put subjective vibes (sunny, cozy, spacious) in 'soft_filters'.
        If you see a feature that matches name (e.g., 'parcare') instead of the raw text.
        Output JSON.
        """

        response = ollama.chat(
            model='llama3.2:3b',
            messages=[
                {'role': 'system', 'content': system_prompt},
                {'role': 'user', 'content': query.text},
            ],
            format=VibeSearch.model_json_schema(),
            options={'temperature': 0}
        )

        raw_output = json.loads(response['message']['content'])

        # Step B: Use the Dependency to normalize Hard Filters
        # This ensures "garaj" becomes "parcare"
        final_hard_filters = mapper.normalize(raw_output.get("hard_filters", []))

        # Step C: Build the final response
        # We'll also build the URL fragment for you
        url_fragment = "-".join(final_hard_filters)
        search_url = f"https://somerealestatewebsite.com/city/q-{url_fragment}/allListings"

        return {
            "original_query": query.text,
            "url_filters": final_hard_filters,
            "vibe_terms": raw_output.get("soft_filters", []),
            "generated_url": search_url
        }

    except Exception as e:
        print(traceback.format_exc())
        raise HTTPException(status_code=500, detail=str(e))

